a = double(subs(A, T, t));     
fprintf('V(T) = %s\n', char(V));
fprintf('A(T) = %s\n', char(A));
fprintf('length(t) = %d , length(v) = %d\n', length(t), length(v));
v5 = double(subs(V, T, 5));
fprintf('\nv(5) = %.4f\n', v5);
